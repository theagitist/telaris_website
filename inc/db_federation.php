 * bytes (NULLs preserved), so callers see the same shape as the MySQL build.
 */
function federation_instance_decode_binary(array $row): array {
    foreach ([
        'public_key', 'previous_public_key', 'operator_email_enc',
        'operator_email_lookup_hash', 'other_contacts_enc',
        'pending_email_enc', 'pending_email_lookup_hash',
    ] as $c) {
