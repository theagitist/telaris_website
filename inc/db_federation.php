        ");
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_ir_operator_lookup ON instance_requests (operator_email_lookup_hash)");
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_ir_status ON instance_requests (status, created_at)");
