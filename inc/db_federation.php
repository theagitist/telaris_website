/**
 * Pluriverse federation schema (stage 2a) + seed helpers (stage 2f-ii onward).
 *
 * Twelve tables, ten idempotent db_ensure_* helpers (instance_status_log and
 * pluriverse_log each pair with a LIKE-copy archive table managed by the same
 * helper). All lazy at first call; reconcile forward without dumps.
 *
 * Spec: P2P federation plan v10 § Schema → Pluriverse-side (line 1144+).
 *
 * Foreign-key topology means several helpers chain into upstream ensures:
 *   - instance_status_log, anomaly_log, key_event_push_attempts → instances
 *   - key_event_push_attempts → key_events_signed
 *
 * 2f-ii adds first-admin seed helpers (db_registry_admins_count,
 * db_seed_registry_admin); these pull in inc/federation/pii.php for PII
 * encryption + lookup hashing.
 */

require_once __DIR__ . '/federation/pii.php';

/**
 * Materialize every federation table in one call. Invoked from
 * bin/setup-app.php and from CLI smoke; future federation endpoints can
 * also call this on first use to bring a fresh database to current state.
 */
function db_ensure_federation_schema(): void {
    // Shared Postgres trigger function first; the per-table ensures attach
    // BEFORE UPDATE triggers to any table carrying updated_at.
    db_ensure_pg_runtime();
    db_ensure_instances_table();
    db_ensure_instance_status_log_tables();
    db_ensure_registry_admins_table();
    db_ensure_magic_link_tokens_table();
    db_ensure_sessions_table();
    db_ensure_blacklists_table();
    db_ensure_anomaly_log_table();
    db_ensure_key_events_signed_table();
    db_ensure_key_event_push_attempts_table();
    db_ensure_pluriverse_log_tables();
    // Self-service control plane (Phase 3): public instance requests, the
    // provisioning job queue the Orrery worker drains, and operator bans.
    db_ensure_instance_requests_table();
    db_ensure_provisioning_jobs_table();
    db_ensure_operator_bans_table();
    db_ensure_pluriverse_settings_table();
}

function db_ensure_instances_table(): void {
    static $checked = false;
    if ($checked) return;
    $checked = true;
    try {
        $pdo = getDB();
        // Fresh-install shape (Postgres). ENUM columns are modelled as VARCHAR
        // with a CHECK constraint; the application layer already validates
        // these values, and VARCHAR+CHECK avoids Postgres CREATE TYPE / ALTER
        // TYPE ... ADD VALUE ceremony when the value set grows.
        $pdo->exec("
            CREATE TABLE IF NOT EXISTS instances (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                hostname VARCHAR(255) NOT NULL,
                url VARCHAR(512) NOT NULL,
                pluriverse_endpoint VARCHAR(512) NOT NULL,
                public_key BYTEA NOT NULL,
                previous_public_key BYTEA NULL,
                key_rotated_at TIMESTAMP NULL,
                rotation_reason VARCHAR(16) NULL CHECK (rotation_reason IS NULL OR rotation_reason IN ('scheduled','operational','compromise')),
                operator_email_enc BYTEA NOT NULL,
                operator_email_lookup_hash BYTEA NOT NULL,
                other_contacts_enc BYTEA NULL,
                pending_email_enc BYTEA NULL,
                pending_email_lookup_hash BYTEA NULL,
                pending_email_requested_at TIMESTAMP NULL,
                label VARCHAR(255) NOT NULL,
                editorial_framing TEXT NULL,
                publishable_slugs JSONB NULL,
                bridges JSONB NULL,
                locale CHAR(2) NOT NULL DEFAULT 'en',
                is_highlighted BOOLEAN NOT NULL DEFAULT FALSE,
                admission_status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (admission_status IN ('pending','verified','published','rejected','blacklisted','outdated','withdrawn','revoked','expired')),
                verify_by_at TIMESTAMP NULL,
                last_seen_at TIMESTAMP NULL,
                health_status VARCHAR(16) NOT NULL DEFAULT 'unknown' CHECK (health_status IN ('up','degraded','down','unknown')),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uniq_hostname UNIQUE (hostname),
                CONSTRAINT uniq_label UNIQUE (label)
            )
        ");
        // Additive column reconciliation (Postgres supports IF NOT EXISTS at
        // the column level natively). These mirror the columns that landed in
        // later releases; on a fresh install they already exist (above) and
        // these are no-ops.
        $pdo->exec("ALTER TABLE instances ADD COLUMN IF NOT EXISTS other_contacts_enc BYTEA NULL");
        $pdo->exec("ALTER TABLE instances ADD COLUMN IF NOT EXISTS locale CHAR(2) NOT NULL DEFAULT 'en'");
        $pdo->exec("ALTER TABLE instances ADD COLUMN IF NOT EXISTS pending_email_enc BYTEA NULL");
        $pdo->exec("ALTER TABLE instances ADD COLUMN IF NOT EXISTS pending_email_lookup_hash BYTEA NULL");
        $pdo->exec("ALTER TABLE instances ADD COLUMN IF NOT EXISTS pending_email_requested_at TIMESTAMP NULL");
        // Non-unique lookup indexes (2p: an operator email may run several
        // instances, so these are plain indexes, not UNIQUE). hostname + label
        // stay UNIQUE via the table constraints above.
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_operator_email_lookup ON instances (operator_email_lookup_hash)");
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_pending_email_lookup ON instances (pending_email_lookup_hash)");
        // BEFORE UPDATE trigger replaces MySQL's ON UPDATE CURRENT_TIMESTAMP.
        db_ensure_pg_runtime();
        db_pg_ensure_updated_at_trigger('instances');
    } catch (PDOException $e) {
        error_log('db_ensure_instances_table: ' . $e->getMessage());
    }
}

